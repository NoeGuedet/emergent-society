import type { Stats } from 'node:fs';
import { lstat } from 'node:fs/promises';
import { join } from 'node:path';
import { loadProviders, type ProviderRegistry } from '../node/tools/providers.js';
import { HostConfigError } from './errors.js';

/**
 * The host's read side of `<home>/providers.json`.
 *
 * The kernel's loader (`src/node/tools/providers.ts`) owns the schema and its
 * value-free refusals; this module adds the two checks a kernel library cannot
 * make for its caller — that the file is a regular same-uid file only its owner
 * can read, and that a refusal reaching the host is a `HostConfigError` the CLI
 * can map to exit 2 — and names the two values the host needs from it.
 *
 * The permission contract is the one the plan states for the credential store:
 * mode 0600 (0400 is also accepted; group and other bits are refused), owned by
 * the invoking uid, a regular file and never a symlink, so a planted link
 * cannot redirect the read. A missing file is refused here (rather than read as
 * an empty registry) because a host without an `llm` entry cannot start; `init`
 * prints this path and the schema hint instead of creating it, so no secret is
 * ever generated by the kernel.
 *
 * The path is `<home>/providers.json` — `cellPaths(home, uid).providersFile`,
 * the same path the layout module and `init` address. `loadProviderStore`
 * delegates a malformed store to the loader's message unchanged (it is already
 * value-free and already starts `invalid providers.json`), and `llmCredentialFrom`
 * yields the one credential literal the frontier journals: `'llm'`.
 */

/** The model endpoint and key, under the credential id the frontier journals. */
export type LlmCredential = {
  readonly endpoint: string; readonly key: string; readonly credentialId: 'llm';
};

const PROVIDERS_BASENAME = 'providers.json';
const LLM_CREDENTIAL_ID = 'llm';

function storePath(home: string): string {
  return join(home, PROVIDERS_BASENAME);
}

/**
 * Refuses a credential store the host must not read.
 *
 * @throws HostConfigError when the file is missing, is a symlink or any other
 * non-regular file, is owned by another uid, grants group or other access, or
 * is not owner-readable.
 */
export async function assertCredentialStore(home: string): Promise<void> {
  const path = storePath(home);
  let entry: Stats;
  try {
    entry = await lstat(path);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') {
      throw new HostConfigError(
        `missing ${path}; create it with mode 0600 and an llm entry`,
      );
    }
    throw err;
  }
  if (!entry.isFile()) {
    throw new HostConfigError(
      `credential store must be a regular file, not a symlink or directory: ${path}`,
    );
  }
  const uid = process.getuid?.();
  if (uid !== undefined && entry.uid !== uid) {
    throw new HostConfigError(`credential store must be owned by uid ${uid}: ${path}`);
  }
  const mode = entry.mode & 0o777;
  if ((mode & 0o077) !== 0) {
    throw new HostConfigError(
      `credential store must not grant group or other access; chmod 600 ${path}`,
    );
  }
  if ((mode & 0o400) === 0) {
    throw new HostConfigError(`credential store must be owner-readable; chmod 600 ${path}`);
  }
}

/**
 * The validated provider registry, once the store itself has been vetted.
 *
 * The loader's own error is re-thrown as `HostConfigError` with the same
 * message: the message is host-authored and value-free, and the CLI keys its
 * exit code off the class, not the text.
 */
export async function loadProviderStore(home: string): Promise<ProviderRegistry> {
  await assertCredentialStore(home);
  try {
    return await loadProviders(home);
  } catch (err) {
    throw new HostConfigError(
      err instanceof Error ? err.message : `invalid ${PROVIDERS_BASENAME}`,
      { cause: err },
    );
  }
}

/**
 * The model credential, or a refusal naming what the store is missing.
 *
 * @throws HostConfigError when the store carries no `llm` entry.
 */
export function llmCredentialFrom(registry: ProviderRegistry): LlmCredential {
  const entry = registry.llm;
  if (entry === undefined) {
    throw new HostConfigError(`providers.json has no "${LLM_CREDENTIAL_ID}" entry`);
  }
  return { endpoint: entry.endpoint, key: entry.key, credentialId: LLM_CREDENTIAL_ID };
}
